package diff

import (
	"fmt"
	"io"
	"strings"
)

// WriteMarkdown renders a GraphDiff as a GitHub-flavored markdown summary
// suitable for posting as a PR comment.
func WriteMarkdown(w io.Writer, gd GraphDiff) error {
	fmt.Fprintf(w, "## Clusterscope Diff: %s\n\n", gd.ClusterName)

	// Summary badges
	var parts []string
	if gd.Summary.Added > 0 {
		parts = append(parts, fmt.Sprintf("**+%d** added", gd.Summary.Added))
	}
	if gd.Summary.Removed > 0 {
		parts = append(parts, fmt.Sprintf("**-%d** removed", gd.Summary.Removed))
	}
	if gd.Summary.Modified > 0 {
		parts = append(parts, fmt.Sprintf("**~%d** modified", gd.Summary.Modified))
	}
	parts = append(parts, fmt.Sprintf("%d unchanged", gd.Summary.Same))
	fmt.Fprintf(w, "%s\n\n", strings.Join(parts, " | "))

	// No changes shortcut
	hasChanges := false
	for _, nd := range gd.Nodes {
		if nd.Kind != Same {
			hasChanges = true
			break
		}
	}
	if !hasChanges {
		fmt.Fprintln(w, "No changes detected.")
		return nil
	}

	// Added nodes
	added := filterNodes(gd.Nodes, Added)
	if len(added) > 0 {
		fmt.Fprintln(w, "### Added")
		for _, nd := range added {
			fmt.Fprintf(w, "- `%s` (%s)", nd.Node.ID, nd.Node.Type)
			if nd.Node.Version != "" {
				fmt.Fprintf(w, " — %s", nd.Node.Version)
			}
			fmt.Fprintln(w)
		}
		fmt.Fprintln(w)
	}

	// Removed nodes
	removed := filterNodes(gd.Nodes, Removed)
	if len(removed) > 0 {
		fmt.Fprintln(w, "### Removed")
		for _, nd := range removed {
			fmt.Fprintf(w, "- ~~`%s`~~ (%s)\n", nd.Node.ID, nd.Node.Type)
		}
		fmt.Fprintln(w)
	}

	// Modified nodes
	modified := filterNodes(gd.Nodes, Modified)
	if len(modified) > 0 {
		fmt.Fprintln(w, "### Modified")
		for _, nd := range modified {
			fmt.Fprintf(w, "- `%s` (%s)\n", nd.Node.ID, nd.Node.Type)
			for _, c := range nd.Changes {
				if c.Old != "" {
					fmt.Fprintf(w, "  - **%s**: `%s` → `%s`\n", c.Field, c.Old, c.New)
				} else {
					fmt.Fprintf(w, "  - **%s**: `%s`\n", c.Field, c.New)
				}
			}
		}
		fmt.Fprintln(w)
	}

	// Edge changes
	addedEdges := filterEdges(gd.Edges, Added)
	removedEdges := filterEdges(gd.Edges, Removed)
	if len(addedEdges) > 0 || len(removedEdges) > 0 {
		fmt.Fprintln(w, "### Edge Changes")
		for _, ed := range addedEdges {
			fmt.Fprintf(w, "- + `%s` → `%s` (%s)\n", ed.Edge.S, ed.Edge.T, ed.Edge.Kind)
		}
		for _, ed := range removedEdges {
			fmt.Fprintf(w, "- - ~~`%s` → `%s`~~ (%s)\n", ed.Edge.S, ed.Edge.T, ed.Edge.Kind)
		}
		fmt.Fprintln(w)
	}

	fmt.Fprintln(w, "---")
	fmt.Fprintln(w, "Generated by [clusterscope](https://github.com/stuttgart-things/clusterscope)")

	return nil
}

func filterNodes(nodes []NodeDiff, kind DiffKind) []NodeDiff {
	var result []NodeDiff
	for _, nd := range nodes {
		if nd.Kind == kind {
			result = append(result, nd)
		}
	}
	return result
}

func filterEdges(edges []EdgeDiff, kind DiffKind) []EdgeDiff {
	var result []EdgeDiff
	for _, ed := range edges {
		if ed.Kind == kind {
			result = append(result, ed)
		}
	}
	return result
}
