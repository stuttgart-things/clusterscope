package diff

import (
	"fmt"
	"io"
	"strings"
)

// mdWriter wraps an io.Writer and captures the first error.
type mdWriter struct {
	w   io.Writer
	err error
}

func (m *mdWriter) printf(format string, args ...any) {
	if m.err != nil {
		return
	}
	_, m.err = fmt.Fprintf(m.w, format, args...)
}

func (m *mdWriter) println(s string) {
	if m.err != nil {
		return
	}
	_, m.err = fmt.Fprintln(m.w, s)
}

// WriteMarkdown renders a GraphDiff as a GitHub-flavored markdown summary
// suitable for posting as a PR comment.
func WriteMarkdown(w io.Writer, gd GraphDiff) error {
	m := &mdWriter{w: w}

	m.printf("## Clusterscope Diff: %s\n\n", gd.ClusterName)

	// Summary badges
	var parts []string
	if gd.Summary.Added > 0 {
		parts = append(parts, fmt.Sprintf("**+%d** added", gd.Summary.Added))
	}
	if gd.Summary.Removed > 0 {
		parts = append(parts, fmt.Sprintf("**-%d** removed", gd.Summary.Removed))
	}
	if gd.Summary.Modified > 0 {
		parts = append(parts, fmt.Sprintf("**~%d** modified", gd.Summary.Modified))
	}
	parts = append(parts, fmt.Sprintf("%d unchanged", gd.Summary.Same))
	m.printf("%s\n\n", strings.Join(parts, " | "))

	// No changes shortcut
	hasChanges := false
	for _, nd := range gd.Nodes {
		if nd.Kind != Same {
			hasChanges = true
			break
		}
	}
	if !hasChanges {
		m.println("No changes detected.")
		return m.err
	}

	// Added nodes
	added := filterNodes(gd.Nodes, Added)
	if len(added) > 0 {
		m.println("### Added")
		for _, nd := range added {
			if nd.Node.Version != "" {
				m.printf("- `%s` (%s) — %s\n", nd.Node.ID, nd.Node.Type, nd.Node.Version)
			} else {
				m.printf("- `%s` (%s)\n", nd.Node.ID, nd.Node.Type)
			}
		}
		m.println("")
	}

	// Removed nodes
	removed := filterNodes(gd.Nodes, Removed)
	if len(removed) > 0 {
		m.println("### Removed")
		for _, nd := range removed {
			m.printf("- ~~`%s`~~ (%s)\n", nd.Node.ID, nd.Node.Type)
		}
		m.println("")
	}

	// Modified nodes
	modified := filterNodes(gd.Nodes, Modified)
	if len(modified) > 0 {
		m.println("### Modified")
		for _, nd := range modified {
			m.printf("- `%s` (%s)\n", nd.Node.ID, nd.Node.Type)
			for _, c := range nd.Changes {
				if c.Old != "" {
					m.printf("  - **%s**: `%s` → `%s`\n", c.Field, c.Old, c.New)
				} else {
					m.printf("  - **%s**: `%s`\n", c.Field, c.New)
				}
			}
		}
		m.println("")
	}

	// Edge changes
	addedEdges := filterEdges(gd.Edges, Added)
	removedEdges := filterEdges(gd.Edges, Removed)
	if len(addedEdges) > 0 || len(removedEdges) > 0 {
		m.println("### Edge Changes")
		for _, ed := range addedEdges {
			m.printf("- + `%s` → `%s` (%s)\n", ed.Edge.S, ed.Edge.T, ed.Edge.Kind)
		}
		for _, ed := range removedEdges {
			m.printf("- - ~~`%s` → `%s`~~ (%s)\n", ed.Edge.S, ed.Edge.T, ed.Edge.Kind)
		}
		m.println("")
	}

	m.println("---")
	m.println("Generated by [clusterscope](https://github.com/stuttgart-things/clusterscope)")

	return m.err
}

func filterNodes(nodes []NodeDiff, kind DiffKind) []NodeDiff {
	var result []NodeDiff
	for _, nd := range nodes {
		if nd.Kind == kind {
			result = append(result, nd)
		}
	}
	return result
}

func filterEdges(edges []EdgeDiff, kind DiffKind) []EdgeDiff {
	var result []EdgeDiff
	for _, ed := range edges {
		if ed.Kind == kind {
			result = append(result, ed)
		}
	}
	return result
}
